#!/usr/bin/env node
// Builds tests/fixtures/xcepta_production_schema.sql — the PRODUCTION database
// STRUCTURE (tables, constraints, RLS policies, grants; no data) from the
// read-only pg_dump in db/schema/production_baseline.sql (git-ignored), adapted
// for PGlite: psql meta-commands, the public-schema creation and Supabase
// platform (supabase_admin) default privileges are removed. Supabase roles and
// the auth schema are provided by tests/helpers/pgliteSecurity.js.
//   node scripts/security/build-test-schema.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const src = readFileSync('db/schema/production_baseline.sql', 'utf8').replace(/^﻿/, '')
const out = src.split(/\r?\n/).filter(l =>
  !l.startsWith(String.fromCharCode(92)) &&            // psql meta-commands (\restrict …)
  !/^SET transaction_timeout/.test(l) &&
  !/^SELECT pg_catalog\.set_config\('search_path'/.test(l) &&
  !/^CREATE SCHEMA public;/.test(l) &&
  !/^COMMENT ON SCHEMA public/.test(l) &&
  !/FOR ROLE supabase_admin/.test(l)).join('\n')
writeFileSync('tests/fixtures/xcepta_production_schema.sql',
  '-- GENERATED by scripts/security/build-test-schema.mjs from the read-only production schema dump\n' +
  '-- (structure only, no data). Test fixture for tests/security.test.js. Do not edit by hand.\n' + out + '\n')
console.log('written tests/fixtures/xcepta_production_schema.sql')
