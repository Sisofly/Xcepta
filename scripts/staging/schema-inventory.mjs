#!/usr/bin/env node
/**
 * schema-inventory.mjs — expected-object inventory from a pg_dump schema file.
 *
 *   node scripts/staging/schema-inventory.mjs <dump.sql> <check.sql> [<drop.sql>]
 *
 * Writes <check.sql>: ONE read-only query (inside BEGIN READ ONLY … ROLLBACK)
 * returning   kind|name|detail|present   for every object the dump creates:
 * tables, constraints, foreign keys, indexes, functions, RLS-enabled flags,
 * policies, and every GRANT (schema usage, function execute, table ALL per
 * role — each table privilege checked individually).
 *
 * Optionally writes <drop.sql>: drops EXACTLY the dump's own tables and
 * functions (used only by the confirmed staging reset), in one transaction.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import process from 'node:process'

const [dumpPath, checkPath, dropPath] = process.argv.slice(2)
if (!dumpPath || !checkPath) { console.error('usage: schema-inventory.mjs <dump.sql> <check.sql> [<drop.sql>]'); process.exit(2) }
const sql = readFileSync(dumpPath, 'utf8').replace(/^﻿/, '')

const unq = s => s.trim().replace(/^"(.*)"$/, '$1')
const lit = s => (s === null || s === undefined ? 'null' : "'" + String(s).replace(/'/g, "''") + "'")
const expected = []
const add = (kind, name, detail = null) => expected.push([kind, name, detail])

for (const m of sql.matchAll(/^-- Name: (.+?); Type: ([A-Z ]+); Schema: public;/gm)) {
  const [, name, type] = m
  if (type === 'TABLE') add('table', unq(name))
  else if (type === 'INDEX') add('index', unq(name))
  else if (type === 'FUNCTION') add('function', unq(name.replace(/\(.*$/, '')))
  else if (type === 'ROW SECURITY') add('rls', unq(name))
  else if (type === 'CONSTRAINT' || type === 'FK CONSTRAINT' || type === 'POLICY') {
    const i = name.indexOf(' ')
    add(type === 'POLICY' ? 'policy' : 'constraint', unq(name.slice(0, i)), unq(name.slice(i + 1)))
  }
}
for (const m of sql.matchAll(/^GRANT ALL ON TABLE public\.(\w+) TO (\w+);/gm)) add('grant_table', m[1], m[2])
for (const m of sql.matchAll(/^GRANT ALL ON FUNCTION public\.([\w]+\([^)]*\)) TO (\w+);/gm)) add('grant_function', m[1], m[2])
for (const m of sql.matchAll(/^GRANT USAGE ON SCHEMA public TO (\w+);/gm)) add('grant_schema', 'public', m[1])

const TABLE_PRIVS = ['SELECT', 'INSERT', 'UPDATE', 'DELETE', 'TRUNCATE', 'REFERENCES', 'TRIGGER']
const check = `-- Generated by scripts/staging/schema-inventory.mjs from ${dumpPath} — READ-ONLY.
begin read only;
with expected(kind, name, detail) as (values
${expected.map(e => '  (' + e.map(lit).join(', ') + ')').join(',\n')}
)
select kind || '|' || name || '|' || coalesce(detail, '') || '|' || (case kind
  when 'table' then exists (select 1 from pg_tables where schemaname = 'public' and tablename = name)
  when 'index' then exists (select 1 from pg_indexes where schemaname = 'public' and indexname = name)
  when 'function' then exists (select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname = 'public' and p.proname = name)
  when 'rls' then exists (select 1 from pg_class c join pg_namespace n on n.oid = c.relnamespace where n.nspname = 'public' and c.relname = name and c.relrowsecurity)
  when 'constraint' then exists (select 1 from pg_constraint k join pg_class t on t.oid = k.conrelid join pg_namespace n on n.oid = t.relnamespace where n.nspname = 'public' and t.relname = name and k.conname = detail)
  when 'policy' then exists (select 1 from pg_policies where schemaname = 'public' and tablename = name and policyname = detail)
  when 'grant_table' then exists (select 1 from pg_tables where schemaname = 'public' and tablename = name)
    and ${TABLE_PRIVS.map(p => `has_table_privilege(detail, 'public.' || name, '${p}')`).join('\n    and ')}
  when 'grant_function' then to_regprocedure('public.' || name) is not null and has_function_privilege(detail, 'public.' || name, 'EXECUTE')
  when 'grant_schema' then has_schema_privilege(detail, name, 'USAGE')
end)::text
from expected order by kind, name, detail;
rollback;
`
writeFileSync(checkPath, check)

if (dropPath) {
  const tables = expected.filter(e => e[0] === 'table').map(e => e[1])
  const fns = [...sql.matchAll(/^CREATE FUNCTION public\.(\w+\([^)]*\))/gm)].map(m => m[1])
  const drop = `-- Generated by scripts/staging/schema-inventory.mjs — STAGING RESET ONLY.
-- Drops exactly the application objects created by ${dumpPath}; nothing else.
begin;
${tables.map(t => `drop table if exists public.${t} cascade;`).join('\n')}
${fns.map(f => `drop function if exists public.${f} cascade;`).join('\n')}
commit;
`
  writeFileSync(dropPath, drop)
}
const counts = expected.reduce((m, e) => ((m[e[0]] = (m[e[0]] || 0) + 1), m), {})
console.log('inventory: ' + Object.entries(counts).map(([k, v]) => k + '=' + v).join(', '))
